"""Phases B-C: integrate the data, build features, run EDA and write reports/eda_report.md.

    python scripts/run_eda.py
"""

from __future__ import annotations

import json
import sys

import pandas as pd

from climate_yield import exploratory_analysis as ea
from climate_yield.config import load_config
from climate_yield.pipeline import prepare_data
from climate_yield.reporting import df_to_markdown


def main() -> int:
    cfg = load_config()
    cfg.ensure_dirs()
    figs = cfg.path("figures_dir")
    data = prepare_data(cfg)
    F, M, panel = data.features, data.modelling, data.panel
    F_obs = F[F["year"] <= 2016]   # climate ends 2016

    dist = ea.yield_distributions(panel, figs)
    trends = ea.yield_trends(panel, figs)
    ea.yield_by_country(panel, figs)
    clim = ea.climate_trends(data.climate_annual, data.baseline, figs)
    cy = ea.climate_yield_scatter(F_obs, figs)
    pest = ea.pesticide_relationships(F_obs, panel, figs)
    corr = ea.correlation_heatmap(M, figs)
    miss = ea.missing_data(panel, M, figs)
    out = ea.outliers(F, figs)
    acf = ea.autocorrelation(F)
    assoc = ea.climate_association(F_obs, figs)
    assoc.to_csv(cfg.path("reports_dir") / "climate_association.csv", index=False)

    tr = trends.groupby("crop")["trend"].median().mul(100).sort_values()
    pooled = assoc[assoc["sample"] == "all crops"].set_index("term")
    sig = assoc[(assoc["sample"] != "all crops") & (assoc["p_value"] < 0.05)]
    high_corr = (corr.where(lambda c: c.abs() > 0.9).stack().reset_index()
                 .query("level_0 < level_1").rename(columns={"level_0": "a", "level_1": "b", 0: "rho"}))

    def fmt_pair(t):
        return f"rho = {t[0]:.3f} (p = {t[1]:.2g})"

    L = ["# Exploratory data analysis", "",
         "Generated by `scripts/run_eda.py`. All numbers below are computed from the integrated panel "
         f"({len(panel):,} yield records, {panel['area'].nunique()} countries, {panel['crop'].nunique()} crops). "
         "Figures are in `reports/figures/eda_*.png`.", "",
         "EDA uses the full period, including the later test years; it was used to understand the data, and the "
         "feature definitions were fixed by prediction-time availability rules rather than by test-period fit.", "",
         "## 1. Yield distribution and crop differences", "",
         f"- Yields span five orders of magnitude and are strongly right-skewed (skewness {dist['skew_raw']:.1f} raw, "
         f"{dist['skew_log']:.2f} after log transform). Models therefore work in log space.",
         "- Median yield by crop (hg/ha): " + ", ".join(f"{k} {v:,.0f}" for k, v in sorted(dist["median_by_crop"].items(), key=lambda kv: kv[1])) + ".",
         "- Root and vegetable crops (carrots, potatoes, cauliflowers, onions) have ~5-10x the per-hectare mass of cereals, "
         "so pooled MAE in hg/ha is dominated by those crops.", "",
         "## 2. Yield trends over time", "",
         "- Median per-series log-linear trend (series with >= 10 years), % per year: "
         + ", ".join(f"{k} {v:.2f}" for k, v in tr.items()) + ".",
         "- Yields grow slowly and steadily for most crops (technology / management trend), so last year's yield is "
         "a strong predictor; the forecasting problem is mostly about year-to-year deviations.", "",
         "## 3. Geography", "",
         "- Only country identifiers exist (no regions, farms or coordinates). Between-country differences are large: "
         "see `eda_wheat_by_country.png` (wheat 2007-2016).", "",
         "## 4. Climate trends", "",
         f"- Median country temperature anomaly vs 1901-1960 averaged {clim['temp_anom_2007_2016']:.2f} deg C in 2007-2016; "
         f"linear trend 1961-2016 {clim['temp_trend_c_per_decade_1961_2016']:.3f} deg C/decade (p = {clim['temp_trend_p']:.1g}).",
         f"- Median rainfall anomaly trend 1961-2016: {clim['rain_trend_pct_per_decade_1961_2016']:.2f} %/decade "
         f"(p = {clim['rain_trend_p']:.2g}).", "",
         "## 5-6. Rainfall, temperature and yield", "",
         f"- Same-year rainfall anomaly vs yield log growth (pooled): {fmt_pair(cy['spearman_growth_vs_rain_anom_pct'])}.",
         f"- Same-year temperature anomaly vs yield log growth (pooled): {fmt_pair(cy['spearman_growth_vs_temp_anom_c'])}.",
         f"- Between-country wheat yield level vs annual rainfall: {fmt_pair(cy['spearman_wheat_level_vs_rain_total_mm'])}; "
         f"vs mean temperature: {fmt_pair(cy['spearman_wheat_level_vs_temp_mean_c'])}. These cross-sectional correlations are "
         "confounded by income, irrigation, soils and technology and must not be read as climate effects.",
         "- First-difference panel regression (change in log yield on change in rainfall / temperature anomaly, crop and "
         "year fixed effects, country-clustered SE):",
         f"  - pooled: {100 * pooled.loc['d_rain10', 'coef']:+.2f}% yield per +10 pp rainfall anomaly "
         f"(95% CI {100 * pooled.loc['d_rain10', 'ci_low']:+.2f} to {100 * pooled.loc['d_rain10', 'ci_high']:+.2f}, p = {pooled.loc['d_rain10', 'p_value']:.2g}); "
         f"{100 * pooled.loc['d_temp', 'coef']:+.2f}% per +1 deg C (95% CI {100 * pooled.loc['d_temp', 'ci_low']:+.2f} to "
         f"{100 * pooled.loc['d_temp', 'ci_high']:+.2f}, p = {pooled.loc['d_temp', 'p_value']:.2g}); n = {int(pooled.loc['d_temp', 'n']):,}.",
         f"  - crop-specific estimates with p < 0.05 (26 tests, no multiple-comparison correction): " + ("; ".join(
             f"{r.sample} {r.term} {100 * r.coef:+.2f}%" for r in sig.itertuples()) or "none") + ".",
         "  - Associations are small relative to the year-to-year noise in yields; country-average calendar-year climate is a "
         "noisy proxy for growing-season weather in cropping regions, which attenuates estimates towards zero. Full table: "
         "`reports/climate_association.csv`.", "",
         "## 7. Pesticides and yield", "",
         f"- Maize yield vs national pesticide tonnes (same year, between and within countries): {fmt_pair(pest['spearman_maize_level'])}. "
         "Pesticide tonnes scale with country size and agricultural intensity, so this mostly reflects development level.",
         f"- Lagged change in pesticide use vs yield change: {fmt_pair(pest['spearman_growth'])} (n = {pest['n_growth']:,}). "
         "No meaningful within-country association is visible.", "",
         "## 8. Predictor correlations", "",
         f"- {len(high_corr)} predictor pairs have |Spearman rho| > 0.9 (lagged log yields with rolling means; "
         "same-year vs lagged and baseline climate). Importance scores will be shared among these.", "",
         "## 9. Missing data", "",
         "- Raw files contain no missing cells; missingness arises from integration: pesticides start in 1990 and are absent "
         "for 28 yield countries; climate ends in 2016; yield series have gaps and different start years.",
         "- Missing share among modelling rows: " + ", ".join(f"{k} {100 * v:.1f}%" for k, v in miss["modelling_missing_share"].items()) + ".",
         "- Missing values are imputed inside the model pipelines (median + missing indicator, fitted on training folds only).", "",
         "## 10. Outliers and data-entry errors", "",
         f"- Year-on-year log growth has kurtosis {out['kurtosis']:.1f}; {100 * out['share_abs_gt_0.5']:.1f}% of changes exceed "
         f"+/-65% (|log| > 0.5) and {100 * out['share_abs_gt_1']:.2f}% exceed a factor of e (~2.7x).",
         "- See `reports/data_quality_report.md` for flat runs (likely FAO estimates) and extreme jumps.", "",
         "## 11. Does the time series support forecasting?", "",
         f"- {acf['n_series']:,} (country, crop) series; median length {acf['series_len_median']:.0f} years; "
         f"{acf['series_ge_30']:,} series have >= 30 observations.",
         f"- Lag-1 autocorrelation of year-on-year growth is {acf['lag1_acf_of_growth']:.3f} (p = {acf['p']:.1g}): shocks partly "
         "reverse the following year (mean reversion), which a model using lagged growth and rolling means can exploit.",
         "- Annual data, one observation per series-year: a one-year-ahead forecast for known (country, crop) series is supported; "
         "seasonal or sub-annual forecasting is not.", "",
         "## Climate association table", "", df_to_markdown(assoc.round(5), "{:.4f}"), ""]
    (cfg.path("reports_dir") / "eda_report.md").write_text("\n".join(L), encoding="utf-8")
    with open(cfg.path("reports_dir") / "eda_summary.json", "w", encoding="utf-8") as fh:
        json.dump({"distribution": dist, "climate": clim, "climate_yield": cy, "pesticides": pest,
                   "missing": miss, "outliers": out, "autocorrelation": acf}, fh, indent=2)
    print("wrote reports/eda_report.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
