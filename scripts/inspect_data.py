"""Phase A: inspect the four raw CSVs and write reports/data_quality_report.md.

    python scripts/inspect_data.py
"""

from __future__ import annotations

import sys

import pandas as pd

from climate_yield import data_integration as di
from climate_yield import data_loader as dl
from climate_yield import data_validation as dv
from climate_yield.config import load_config
from climate_yield.pipeline import prepare_data
from climate_yield.reporting import df_to_markdown


def section_for(name: str, raw: pd.DataFrame, fname: str) -> list[str]:
    prof = dv.profile(raw)
    rep = dv.validate_raw(name, raw)
    out = [f"## `{fname}` ({prof['rows']:,} rows x {prof['columns']} columns)", ""]
    out.append("| column | dtype | missing | distinct |")
    out.append("|---|---|---|---|")
    for c in raw.columns:
        out.append(f"| {c} | {prof['dtypes'][c]} | {prof['missing'][c]} | {raw[c].nunique():,} |")
    out += ["", f"- Exact duplicate rows: **{prof['duplicate_rows']}**",
            f"- Duplicate keys on {dv.KEYS[name]}: **{int(raw.duplicated(dv.KEYS[name]).sum())}**",
            f"- Year coverage: **{raw['Year'].min()}-{raw['Year'].max()}**",
            f"- Schema validation errors: {rep.errors or 'none'}",
            f"- Warnings: {rep.warnings or 'none'}", ""]
    for c in ("Domain", "Element", "Item", "Unit", "Statistics"):
        if c in raw and raw[c].nunique() <= 20:
            vc = raw[c].value_counts()
            out.append(f"- `{c}` values: " + ", ".join(f"{k} ({v:,})" for k, v in vc.items()))
    out += ["", "Numeric summary:", "", df_to_markdown(prof["numeric_summary"].reset_index().rename(columns={"index": "column"}), "{:,.2f}"), ""]
    out += ["Representative records:", "", df_to_markdown(raw.sample(5, random_state=0).reset_index(drop=True), "{:,.4g}"), ""]
    return out


def main() -> int:
    cfg = load_config()
    cfg.ensure_dirs()
    raw = dl.load_raw_tables(cfg)
    tidy = dl.load_tidy_tables(cfg, raw)
    y = tidy["yield"]
    L = ["# Data quality report", "",
         "Generated by `scripts/inspect_data.py` from the four original CSV files (which are never modified).", ""]
    for name in ("yield", "pesticides", "rainfall", "temperature"):
        L += section_for(name, raw[name], cfg["raw_files"][name])

    L += ["## Yield-specific findings", ""]
    per_crop = y.groupby("crop").agg(rows=("year", "size"), areas=("area", "nunique"), first=("year", "min"),
                                     last=("year", "max"), median_hg_ha=("yield_hg_ha", "median")).reset_index()
    L += ["Observations per crop:", "", df_to_markdown(per_crop, "{:,.0f}"), ""]
    sl = y.groupby(["area", "crop"]).size()
    L += [f"- (area, crop) series: **{len(sl):,}**; observations per series: median {sl.median():.0f}, "
          f"min {sl.min()}, max {sl.max()}; series with the full 59 years: {(sl == 59).sum():,}.",
          f"- Rows per year range from {y.groupby('year').size().min():,} to {y.groupby('year').size().max():,}.",
          f"- Zero yields: {(y.yield_hg_ha == 0).sum()} rows "
          f"({', '.join(f'{r.crop} / {r.area} / {r.year}' for r in y[y.yield_hg_ha == 0].itertuples())}). "
          "These are removed (log undefined; a harvested-area yield of exactly zero is implausible).",
          f"- Smallest positive yield: {y[y.yield_hg_ha > 0].yield_hg_ha.min():,.0f} hg/ha; largest: {y.yield_hg_ha.max():,.0f} hg/ha "
          f"({y.loc[y.yield_hg_ha.idxmax(), 'crop']} / {y.loc[y.yield_hg_ha.idxmax(), 'area']} / {y.loc[y.yield_hg_ha.idxmax(), 'year']}).", ""]
    runs = dv.constant_runs(y, 5)
    L += [f"- **Flat runs**: {len(runs):,} runs of >= 5 consecutive identical yields in {runs[['area', 'crop']].drop_duplicates().shape[0]:,} series "
          f"(covering {int(runs['length'].sum()):,} rows). Identical values over many years indicate FAO estimates or carried-forward "
          "figures rather than measurements. They are kept (no defensible way to recover the true values) but flagged as a limitation.",
          ""]
    jumps = dv.extreme_jumps(y, 5.0)
    L += [f"- **Extreme year-on-year jumps** (>5x or <1/5x vs previous year): {len(jumps)} rows. Examples:", "",
          df_to_markdown(jumps.sort_values("ratio").iloc[list(range(3)) + list(range(-3, 0))].reset_index(drop=True), "{:,.2f}"), "",
          "These are kept but are a major source of large forecast errors; no external evidence is available to "
          "decide which are data-entry errors.", ""]
    L += ["## Aggregate / historical areas", "",
          "- FAO `China` is an aggregate (mainland + Taiwan + Hong Kong + Macao); wheat 2010: China 47,484 vs China, mainland 47,486 hg/ha. "
          "It is excluded to avoid double counting; World Bank `China` is matched to `China, mainland`.",
          "- Historical FAO entities (USSR, Czechoslovakia, Yugoslav SFR, Ethiopia PDR, Sudan (former), Belgium-Luxembourg, "
          "Serbia and Montenegro) have no climate series and are excluded from the modelling panel.", ""]

    L += ["## Units and interpretation", "",
          "| file | variable | unit | evidence | interpretation |", "|---|---|---|---|---|",
          "| yield.csv | Value | hg/ha (hectogram per hectare; 10,000 hg/ha = 1 t/ha) | `Unit` column, single value | FAO crop yield = production / harvested area. Kept in hg/ha. |",
          "| pesticides.csv | Value | tonnes | `Unit` column; `Item` = Pesticides (total); `Element` = Agricultural Use | National total active-ingredient use for all crops. **Not** per hectare and not crop-specific. |",
          "| rainfall.csv | Rainfall - (MM) | mm | column header | Monthly precipitation for the country (label `<Mon> Average` = country-average). Monthly values summed to annual totals (mean annual total ~1,240 mm). The source does not document whether values are area-weighted; this is an assumption. |",
          "| temp.csv | Temperature - (Celsius) | deg C | column header | Monthly mean near-surface temperature, country average. Averaged (not summed) to annual statistics. No daily min/max temperature exists. |",
          "", "## Join keys", "",
          "- yield and pesticides share FAO area names exactly (except Bermuda, China Macao SAR, Samoa, Seychelles which have pesticide data but no yield).",
          f"- rainfall and temp are row-aligned (same Country/Year/Statistics in the same order: "
          f"{bool((raw['rainfall'][['Country', 'Year', 'Statistics']].values == raw['temperature'][['Country', 'Year', 'Statistics']].values).all())}).",
          f"- {len(di.COUNTRY_NAME_MAP)} World Bank country names required explicit mapping to FAO names (see `data_integration.COUNTRY_NAME_MAP`).",
          "- No crop identifier exists in the climate or pesticide files, and no sub-national geography exists anywhere: "
          "the finest common resolution is **country x calendar year**.", ""]

    data = prepare_data(cfg)
    rep = data.integration_report
    L += ["## Integration summary", ""]
    for k, v in rep.items():
        L.append(f"- **{k}**: {v}")
    L.append("")
    (cfg.path("reports_dir") / "data_quality_report.md").write_text("\n".join(L), encoding="utf-8")
    runs.to_csv(cfg.path("reports_dir") / "flat_yield_runs.csv", index=False)
    jumps.to_csv(cfg.path("reports_dir") / "extreme_yield_jumps.csv", index=False)
    print("wrote reports/data_quality_report.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
